package com.hexnext.themer.shizuku

import com.hexnext.themer.BuildConfig

/**
 * POSIX sh stability watchdog written to `/data/local/tmp/hexnext/monitor.sh` (`hexnext_owner`
 * in the owner build, see [DIR]) and started
 * detached (setsid + nohup) by [ThemeService.startStabilityMonitor].
 *
 * Usage: `sh monitor.sh <seconds>`. Every 5 s it samples `pidof system_server` and
 * `pidof com.android.systemui`. A pid that changes to a new non-empty value counts as one
 * restart (an empty reading while the process is down is ignored). Two or more restarts of
 * either process inside the window disable every `HexNext*` overlay from `cmd overlay list`
 * and write `safe_mode.json` {"reason":"...","time":<epoch>}. `monitor_status.json` is
 * rewritten on every tick and always on exit (completed / safe_mode / stopped).
 *
 * It runs as root while [DIR] belongs to the shell (uid 2000), so any shell process can put a
 * symlink in it under a name the monitor writes. The script therefore works inside [DIR] only
 * after `cd -P` and a `pwd -P` check (a symlinked [DIR] stops it), and writes every file through
 * `put`: a new file under a random name, created with `set -C` (O_EXCL) and umask 022, then
 * renamed over the target. Nothing is written or chmod-ed through a name a shell process could
 * have planted beforehand.
 *
 * The text uses `£` in place of the shell dollar sign so that Kotlin string templates never
 * touch it; [text] swaps it back.
 */
internal object MonitorScript {

    /**
     * The shell-owned state directory. Each flavor has its own ([BuildConfig.ROOT_STATE_SUFFIX]:
     * none for Play, `_owner` for the owner build), so the two builds installed side by side never
     * share a monitor, its pid file or the safe-mode and font state.
     */
    const val DIR = "/data/local/tmp/hexnext" + BuildConfig.ROOT_STATE_SUFFIX
    const val PATH = "$DIR/monitor.sh"
    const val PID_FILE = "$DIR/monitor.pid"
    const val STATUS_FILE = "$DIR/monitor_status.json"
    const val SAFE_MODE_FILE = "$DIR/safe_mode.json"

    val text: String by lazy { TEMPLATE.trimIndent().replace('£', '$') + "\n" }

    private const val TEMPLATE = """
        #!/system/bin/sh
        # Hex Next stability monitor. Generated by ThemeService; plain POSIX sh.
        set -f
        umask 022
        DIR=$DIR
        DURATION=£{1:-120}
        INTERVAL=5
        STATUS=monitor_status.json
        PIDFILE=monitor.pid
        START=£(date +%s)
        SS_CHANGES=0
        UI_CHANGES=0
        SAMPLES=0
        RESULT=running
        REASON=none

        # put NAME FORMAT ARGS...: printf into a fresh, unguessable file, then rename it over NAME.
        put() {
          put_name=£1
          shift
          put_tmp=".£put_name.£(cat /proc/sys/kernel/random/uuid 2>/dev/null).££.£RANDOM£RANDOM.tmp"
          if ( set -C; printf "£@" > "£put_tmp" ) 2>/dev/null; then
            mv -f "£put_tmp" "£put_name" && return 0
          fi
          rm -f "£put_tmp"
          return 1
        }

        write_status() {
          NOW=£(date +%s)
          put "£STATUS" '{"state":"%s","reason":"%s","started":%s,"updated":%s,"durationSeconds":%s,"samples":%s,"systemServerChanges":%s,"systemUiChanges":%s,"systemServerPid":"%s","systemUiPid":"%s","pid":%s}\n' \
            "£1" "£REASON" "£START" "£NOW" "£DURATION" "£SAMPLES" "£SS_CHANGES" "£UI_CHANGES" "£LAST_SS" "£LAST_UI" "££"
        }

        release_pid() {
          if [ "£(cat "£PIDFILE" 2>/dev/null)" = "££" ]; then
            rm -f "£PIDFILE"
          fi
        }

        on_term() {
          REASON=stopped_by_app
          write_status stopped
          release_pid
          exit 0
        }
        trap on_term TERM INT HUP

        disable_hex() {
          tries=0
          while [ "£tries" -lt 12 ]; do
            LIST=£(cmd overlay list --user current 2>/dev/null)
            if [ -n "£LIST" ]; then
              printf '%s\n' "£LIST" | while IFS= read -r line; do
                case "£line" in
                  *"["*"]"*|*---*) ;;
                  *) continue ;;
                esac
                id=""
                for word in £line; do id=£word; done
                name=£{id#*:}
                case "£name" in
                  HexNext*) cmd overlay disable --user current "£id" >/dev/null 2>&1 ;;
                esac
              done
              return 0
            fi
            tries=£((tries + 1))
            sleep 5
          done
          return 1
        }

        mkdir -p "£DIR"
        cd -P "£DIR" 2>/dev/null && [ "£(pwd -P)" = "£DIR" ] || exit 1
        put "£PIDFILE" '%s\n' "££"
        LAST_SS=£(pidof system_server)
        LAST_UI=£(pidof com.android.systemui)
        END=£((START + DURATION))
        write_status running

        while [ "£(date +%s)" -lt "£END" ]; do
          sleep "£INTERVAL" &
          wait £!
          SAMPLES=£((SAMPLES + 1))
          SS=£(pidof system_server)
          UI=£(pidof com.android.systemui)
          if [ -n "£SS" ]; then
            if [ -z "£LAST_SS" ]; then
              LAST_SS=£SS
            elif [ "£SS" != "£LAST_SS" ]; then
              SS_CHANGES=£((SS_CHANGES + 1))
              LAST_SS=£SS
            fi
          fi
          if [ -n "£UI" ]; then
            if [ -z "£LAST_UI" ]; then
              LAST_UI=£UI
            elif [ "£UI" != "£LAST_UI" ]; then
              UI_CHANGES=£((UI_CHANGES + 1))
              LAST_UI=£UI
            fi
          fi
          if [ "£SS_CHANGES" -ge 2 ] || [ "£UI_CHANGES" -ge 2 ]; then
            REASON="system_server restarted £SS_CHANGES times and SystemUI £UI_CHANGES times within £DURATION s of a Hex Next apply"
            disable_hex
            put safe_mode.json '{"reason":"%s","time":%s}\n' "£REASON" "£(date +%s)"
            RESULT=safe_mode
            break
          fi
          write_status running
        done

        if [ "£RESULT" = running ]; then
          RESULT=completed
          REASON=stable
        fi
        write_status "£RESULT"
        release_pid
        exit 0
    """
}
